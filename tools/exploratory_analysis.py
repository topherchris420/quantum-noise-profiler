"""Exploratory (NOT preregistered) breakdowns of recorded v0.2 runs.

Prints, per Experiment E scenario and context mode, which alert channel
(drift / threshold / forecast) produced the false alerts, and when; and,
for Experiment A, the time of the first false alert. Everything is computed
from the recorded raw files. Results from this script are labelled
exploratory wherever they are quoted.

    python tools/exploratory_analysis.py > results/V02_EXPLORATORY.md
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))

from v02.compact import first_true, v02_channel_alarms  # noqa: E402

R = ROOT / "results"


def latest(name):
    out = None
    for line in (R / "runs.jsonl").read_text().splitlines():
        if line.strip():
            e = json.loads(line)
            if e["experiment"] == name and not e.get("config", {}).get("smoke"):
                out = e
    return out


def trials(e):
    p = R / "raw" / Path(e["raw"]).name
    return [json.loads(x) for x in gzip.decompress(p.read_bytes()).decode().splitlines() if x.strip()]


def main():
    print("# Exploratory analyses (not preregistered)\n")
    print("Generated by `tools/exploratory_analysis.py` from recorded raw data. These breakdowns were chosen after")
    print("seeing the preregistered results and must not be read as confirmatory.\n")
    e = latest("V02_E_workload_shift")
    if e is not None:
        c_star = e["config"]["calibrated"]["c_star"]
        shift = e["config"]["shift_at"]
        print(
            f"## Experiment E: which channel raised the false alerts (`{e['run_id']}`, v0.2 calibrated, c*={c_star})\n"
        )
        print("| Scenario | mode | any | drift | threshold | forecast | median first-alert batch | runs |")
        print("|---|---|---|---|---|---|---|---|")
        ts = trials(e)
        for sc in e["config"]["scenarios"]:
            for mode in ("bucket", "exact"):
                recs = [{"v02": t["v02"][mode]} for t in ts if t["scenario"] == sc]
                ch = {}
                firsts = []
                for name in ("drift", "threshold", "forecast"):
                    flags = []
                    for r in recs:
                        qs = sorted(int(q) for q in r["v02"]["q"])
                        if sc == "E7":
                            qs = [q for q in qs if q != 0]
                        flags.append(any(any(v02_channel_alarms(r, q, c_star, name)) for q in qs))
                    ch[name] = float(np.mean(flags))
                anyf = []
                for r in recs:
                    qs = sorted(int(q) for q in r["v02"]["q"])
                    if sc == "E7":
                        qs = [q for q in qs if q != 0]
                    fi = []
                    for q in qs:
                        flags = [
                            any(x)
                            for x in zip(
                                *(v02_channel_alarms(r, q, c_star, n) for n in ("drift", "threshold", "forecast"))
                            )
                        ]
                        f = first_true(flags, 0, None, r["v02"]["i"])
                        if f is not None:
                            fi.append(f)
                    anyf.append(bool(fi))
                    if fi:
                        firsts.append(min(fi))
                med = float(np.median(firsts)) if firsts else None
                label = sc + (" (q1 only)" if sc == "E7" else "")
                print(
                    f"| {label} | {mode} | {np.mean(anyf):.2f} | {ch['drift']:.2f} | {ch['threshold']:.2f} | "
                    f"{ch['forecast']:.2f} | {med} | {len(recs)} |"
                )
        print(
            f"\nWorkload change at batch {shift}. In exact mode the post-change contexts are new series with no baseline,"
        )
        print(
            "so a drift alert cannot fire on them before the drift channel's minimum baseline; a threshold alert can.\n"
        )
        print("Contexts seen on qubit 0 after the change (first run):\n")
        for sc in e["config"]["scenarios"]:
            t = next(t for t in ts if t["scenario"] == sc)
            print(f"- {sc}: bucket {t['contexts']['bucket']['after']}; exact {t['contexts']['exact']['after']}")
        print()
    a = latest("V02_A_false_alarm")
    if a is not None:
        c_star = a["config"]["calibrated"]["c_star"]
        print(f"## Experiment A: when do false alerts occur? (`{a['run_id']}`)\n")
        print("| Condition | config | runs with a false alert | first-alert batch quartiles |")
        print("|---|---|---|---|")
        for cond in a["config"]["conditions"]:
            ts = [t for t in trials(a) if t["cond"] == cond]
            for name, c in (("v0.2 anytime-valid", 0.0), ("v0.2 calibrated", c_star)):
                firsts = []
                for t in ts:
                    fi = []
                    for q in (0, 1):
                        flags = [
                            any(x)
                            for x in zip(*(v02_channel_alarms(t, q, c, n) for n in ("drift", "threshold", "forecast")))
                        ]
                        f = first_true(flags, 0, None, t["v02"]["i"])
                        if f is not None:
                            fi.append(f)
                    if fi:
                        firsts.append(min(fi))
                q = np.quantile(firsts, [0.25, 0.5, 0.75]).tolist() if firsts else None
                print(f"| {cond} | {name} | {len(firsts)}/{len(ts)} | {q} |")
        print()


if __name__ == "__main__":
    main()
