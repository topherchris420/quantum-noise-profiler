"""Generate results/V02_TABLES.md from the recorded v0.2 runs (no hand-copied numbers).

python tools/make_summary_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
METHODS = ["v02", "v02cal", "v01", "v01cal", "shewhart", "cusum"]
NAME = {
    "v02": "v0.2 anytime-valid",
    "v02cal": "v0.2 calibrated",
    "v01": "v0.1",
    "v01cal": "v0.1 re-thresholded",
    "shewhart": "Shewhart",
    "cusum": "CUSUM",
    "naive": "naive threshold",
}


def latest():
    out = {}
    for line in (R / "runs.jsonl").read_text().splitlines():
        if line.strip():
            e = json.loads(line)
            if not (e.get("config", {}).get("smoke") or "SMOKE" in e.get("notes", "")):
                out[e["experiment"]] = e
    return out


def ci(r):
    return f"{r['rate']:.3f} [{r['ci95'][0]:.3f}, {r['ci95'][1]:.3f}] ({r['k']}/{r['n']})"


def fmt(x, nd=3):
    if x is None:
        return "-"
    if isinstance(x, float):
        return f"{x:.{nd}g}" if abs(x) < 1000 else f"{x:.0f}"
    return str(x)


def criteria_table(e):
    rows = ["| Criterion | Description | Observed | Required | Result |", "|---|---|---|---|---|"]
    for c in e["criteria"]:
        rows.append(
            f"| {c['name']} | {c['description'].replace('|', chr(92) + '|')} | {c['observed']:.4g} | {c['comparison']} {c['threshold']:g} | "
            f"{'PASS' if c['passed'] else 'FAIL'} |"
        )
    return "\n".join(rows)


def main():
    L = latest()
    out = [
        "# v0.2 result tables",
        "",
        "Generated by `tools/make_summary_tables.py` from `results/runs.jsonl`; do not edit by hand.",
        "",
    ]
    total = passed = 0
    for exp in (
        "V02_A_false_alarm",
        "V02_B_gradual",
        "V02_C_abrupt",
        "V02_D_misspecification",
        "V02_E_workload_shift",
        "V02_F_cross_framework",
    ):
        if exp in L:
            total += len(L[exp]["criteria"])
            passed += sum(c["passed"] for c in L[exp]["criteria"])
    out += [f"**Preregistered criteria: {passed} of {total} passed.**", ""]
    if "V02_calibration" in L:
        e = L["V02_calibration"]
        s = e["summary"]
        out += [
            f"## Calibration (`{e['run_id']}`)",
            "",
            "| Method | Chosen | Max calibration false-alert rate over K1-K4 |",
            "|---|---|---|",
        ]
        for m, k in (("v02cal", "c_star"), ("shewhart", "k_star"), ("cusum", "h_star"), ("v01cal", "b_star")):
            out.append(f"| {NAME[m]} | {k} = {s['chosen'][k]} | {fmt(s['chosen_max_fa'][m])} |")
        out += [
            "",
            "v0.2 with anytime-valid thresholds (c = 0): "
            + ", ".join(f"{k} {v:.3f}" for k, v in s["v02_nominal_fa"].items()),
            "",
        ]
    if "V02_A_false_alarm" in L:
        e = L["V02_A_false_alarm"]
        s = e["summary"]
        out += [
            f"## Experiment A — sequential false-alarm control (`{e['run_id']}`)",
            "",
            criteria_table(e),
            "",
            "Run-level false-alert rate, Wilson 95% interval (alerts/runs):",
            "",
            "| Condition | " + " | ".join(NAME[m] for m in METHODS) + " |",
            "|---" * (len(METHODS) + 1) + "|",
        ]
        for cond, r in s.items():
            out.append(
                f"| {cond} ({r['n_batches']} batches) | "
                + " | ".join(ci(r[m]["run_false_alert"]) if m in r else "-" for m in METHODS)
                + " |"
            )
        out += [
            "",
            "False-alert batches per monitoring hour:",
            "",
            "| Condition | " + " | ".join(NAME[m] for m in METHODS) + " |",
            "|---" * (len(METHODS) + 1) + "|",
        ]
        for cond, r in s.items():
            out.append(
                f"| {cond} | "
                + " | ".join(fmt(r[m]["false_alert_batches_per_hour"]) if m in r else "-" for m in METHODS)
                + " |"
            )
        out += [
            "",
            "Per-channel run-level false-alert rates (v0.2):",
            "",
            "| Condition | config | drift | threshold | forecast |",
            "|---|---|---|---|---|",
        ]
        for cond, r in s.items():
            for m in ("v02", "v02cal"):
                ch = r[m]["per_channel_run_false_alert"]
                out.append(f"| {cond} | {NAME[m]} | {ch['drift']:.3f} | {ch['threshold']:.3f} | {ch['forecast']:.3f} |")
        out.append("")
    if "V02_B_gradual" in L:
        e = L["V02_B_gradual"]
        s = e["summary"]
        out += [f"## Experiment B — gradual degradation (`{e['run_id']}`)", "", criteria_table(e), ""]
        for cond in ("B1", "B2"):
            r = s[cond]
            out += [
                f"**{cond}** (true crossing at batch {r['i_cross']:.2f}):",
                "",
                "| Method | detected | early (95% CI) | median lead (min) [IQR] | first alert batch median [IQR] | q1 false-alert runs | q1 false alerts / h |",
                "|---|---|---|---|---|---|---|",
            ]
            for m in [*METHODS, "naive"]:
                if m not in r:
                    continue
                x = r[m]
                fa = x["first_alert_batch"]
                out.append(
                    f"| {NAME[m]} | {x['detect_rate']:.3f} | {ci(x['early_detection'])} | "
                    f"{fmt(x['median_lead_min'])} [{fmt(x['lead_q25_min'])}, {fmt(x['lead_q75_min'])}] | "
                    f"{fmt(fa['median'])} [{fmt(fa['q25'])}, {fmt(fa['q75'])}] | {ci(x['q1_run_false_alert'])} | "
                    f"{fmt(x['q1_false_alert_batches_per_hour'])} |"
                )
            out.append("")
        pc = s["pooled_forecast_coverage_80"]
        out += [
            "Coverage of 80% predictive crossing intervals (forecasts issued before the true crossing): "
            + "; ".join(f"{NAME[m]} {ci(v)}" for m, v in pc.items() if v),
            "",
        ]
    if "V02_C_abrupt" in L:
        e = L["V02_C_abrupt"]
        s = e["summary"]
        out += [
            f"## Experiment C — abrupt degradation (`{e['run_id']}`)",
            "",
            criteria_table(e),
            "",
            "| Step | Method | within 5 | within 6 | within 24 | median delay [IQR] | detected given clean pre-step | run false alert |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for cond in ("x1.5", "x1.2", "x1.1"):
            for m in METHODS:
                if m not in s[cond]:
                    continue
                x = s[cond][m]
                d = x["delay"]
                out.append(
                    f"| {cond} | {NAME[m]} | {x['within_5']['rate']:.3f} | {x['within_6']['rate']:.3f} | "
                    f"{x['within_24']['rate']:.3f} | {fmt(d['median'])} [{fmt(d['q25'])}, {fmt(d['q75'])}] | "
                    f"{fmt(x['detect_rate_given_clean_prestep'])} | {x['run_false_alert']['rate']:.3f} |"
                )
        out += [
            "",
            "Pooled run-level false-alert rate: "
            + "; ".join(f"{NAME[m]} {ci(v)}" for m, v in s["pooled_run_false_alert"].items()),
            "",
        ]
    if "V02_D_misspecification" in L:
        e = L["V02_D_misspecification"]
        s = e["summary"]
        out += [
            f"## Experiment D — T1 misspecification (`{e['run_id']}`)",
            "",
            criteria_table(e),
            "",
            "| Scenario | n | OK | INSUFFICIENT_EVIDENCE | MODEL_MISSPECIFICATION | coverage among OK | false confidence | main reason codes |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for sc, r in s.items():
            codes = ", ".join(f"{k} {v}" for k, v in sorted(r["reason_codes"].items(), key=lambda kv: -kv[1])[:3])
            out.append(
                f"| {sc} | {r['n']} | {r['ok']} | {r['insufficient_evidence']} | {r['model_misspecification']} | "
                f"{fmt(r['coverage_among_ok'])} | {r['false_confidence_rate']:.3f} | {codes} |"
            )
        out.append("")
    if "V02_E_workload_shift" in L:
        e = L["V02_E_workload_shift"]
        s = e["summary"]
        out += [
            f"## Experiment E — workload shift (`{e['run_id']}`)",
            "",
            criteria_table(e),
            "",
            "| Scenario | bucket, v0.2 | bucket, v0.2 calibrated | exact, v0.2 | exact, v0.2 calibrated |",
            "|---|---|---|---|---|",
        ]
        for sc, r in s.items():
            cells = []
            for mode in ("bucket", "exact"):
                for m in ("v02", "v02cal"):
                    x = r[mode][m]
                    v = x.get("q0_detection_after_shift") if sc == "E7" else x["run_false_alert"]
                    cells.append(ci(v))
            out.append(f"| {sc}{' (q0 detection)' if sc == 'E7' else ''} | " + " | ".join(cells) + " |")
        out.append("")
    if "V02_F_cross_framework" in L:
        e = L["V02_F_cross_framework"]
        s = e["summary"]
        cm = s["comparison"]
        out += [
            f"## Experiment F — Qiskit vs Cirq (`{e['run_id']}`)",
            "",
            criteria_table(e),
            "",
            "| (qubit:context) | Qiskit - Cirq mean rate | SE | z | CI-width ratio |",
            "|---|---|---|---|---|",
        ]
        for k, v in cm["per_context"].items():
            out.append(f"| {k} | {v['diff']:.2e} | {v['se']:.2e} | {v['z']:.2f} | {v['width_ratio']:.3f} |")
        fw = s["frameworks"]
        out += [
            "",
            f"F1 false-alert rate: Qiskit {ci(fw['qiskit']['F1']['run_false_alert'])}, Cirq "
            f"{ci(fw['cirq']['F1']['run_false_alert'])}. F2 within 6 batches: Qiskit "
            f"{ci(fw['qiskit']['F2']['within_6'])}, Cirq {ci(fw['cirq']['F2']['within_6'])}.",
            "",
        ]
    (R / "V02_TABLES.md").write_text("\n".join(out) + "\n")
    print(f"wrote results/V02_TABLES.md ({passed}/{total} criteria passed)")


if __name__ == "__main__":
    main()
